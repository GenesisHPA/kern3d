// Regenerates the single-line (engraving) font data modules in
// packages/app/src/laser/strokeFonts/ from their upstream files:
//
//   node scripts/stroke-fonts.mjs <sources dir>
//
// The sources dir holds, as downloaded:
//   Hershey fonts (https://github.com/kamalmostafa/hershey-fonts, hershey-fonts/*.jhf):
//     futural.jhf futuram.jhf timesr.jhf scripts.jhf gothiceng.jhf cyrillic.jhf
//   OpenGOST single-line, LibreCAD (librecad/support/fonts, SIL OFL 1.1):
//     lc_opengost-ar.lff lc_opengost-br.lff
//   Relief SingleLine (https://github.com/isdat-type/Relief-SingleLine, SIL OFL 1.1):
//     ReliefSingleLineSVG-Regular.svg (fonts/open_svg)
//
// Each font becomes a module exporting its data as one string, imported on demand.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2];
if (!src) {
    console.error("usage: node scripts/stroke-fonts.mjs <sources dir>");
    process.exit(1);
}
const out = join(import.meta.dirname, "..", "packages", "app", "src", "laser", "strokeFonts");

const HEADER = `// Part of the Chili3d Project, under the AGPL-3.0 License.
// See LICENSE file in the project root for full license information.
// Generated by scripts/stroke-fonts.mjs — do not edit.
`;

function write(name, comment, data) {
    const text = `${HEADER}//\n${comment
        .split("\n")
        .map((l) => `// ${l}`.trimEnd())
        .join("\n")}\n\nconst data: string =\n    ${JSON.stringify(data)};\nexport default data;\n`;
    writeFileSync(join(out, `${name}.ts`), text);
    console.log(`${name}.ts: ${text.length} bytes`);
}

// Hershey: the .jhf records joined (the files wrap long glyphs over lines), one per line
const HERSHEY_NOTE = `The Hershey Fonts were originally created by Dr. A. V. Hershey while working at the
U. S. National Bureau of Standards. The format of the Font data in this distribution was
originally created by James Hurt, Cognition, Inc., 900 Technology Park Drive, Billerica,
MA 01821. (Data from https://github.com/kamalmostafa/hershey-fonts; see THIRD_PARTY_NOTICES.md.)`;

function jhf(file) {
    const text = readFileSync(join(src, file), "latin1").replace(/\r?\n/g, "");
    const records = [];
    let i = 0;
    while (i < text.length) {
        const count = Number.parseInt(text.slice(i + 5, i + 8), 10);
        records.push(text.slice(i + 5, i + 8 + 2 * count));
        i += 8 + 2 * count;
    }
    return records.join("\n");
}

for (const [name, file] of [
    ["hersheySans", "futural.jhf"],
    ["hersheySansBold", "futuram.jhf"],
    ["hersheySerif", "timesr.jhf"],
    ["hersheyScript", "scripts.jhf"],
    ["hersheyGothic", "gothiceng.jhf"],
    ["hersheyCyrillic", "cyrillic.jhf"],
]) {
    write(name, `${file}\n${HERSHEY_NOTE}`, jhf(file));
}

// LibreCAD fonts: the metric header lines and the glyphs, comments and blank lines dropped
function lff(file) {
    const keep = [];
    for (const line of readFileSync(join(src, file), "utf8").split(/\r?\n/)) {
        const t = line.trim();
        if (t === "") continue;
        if (t.startsWith("#") && !/^#\s*(LetterSpacing|WordSpacing|LineSpacingFactor)\s*:/i.test(t)) continue;
        keep.push(t);
    }
    return keep.join("\n");
}

const GOST_NOTE = `OpenGOST single-line, LibreCAD font by stranger573 <stranger573@mail.ru>,
SIL Open Font License 1.1 (see THIRD_PARTY_NOTICES.md).`;
write("gostA", `lc_opengost-ar.lff — GOST 2.304 type A\n${GOST_NOTE}`, lff("lc_opengost-ar.lff"));
write("gostB", `lc_opengost-br.lff — GOST 2.304 type B\n${GOST_NOTE}`, lff("lc_opengost-br.lff"));

// Relief SingleLine SVG font: "units-per-em cap-height" then one glyph per line, "code advance d"
function svgFont(file) {
    const text = readFileSync(join(src, file), "utf8");
    const upm = /units-per-em="([\d.]+)"/.exec(text)?.[1] ?? "1000";
    const cap = /cap-height="([\d.]+)"/.exec(text)?.[1] ?? "700";
    const fallbackAdvance = /<font[^>]*horiz-adv-x="([\d.]+)"/.exec(text)?.[1] ?? "500";
    const lines = [`${upm} ${cap}`];
    const decode = (u) =>
        u
            .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(Number.parseInt(h, 16)))
            .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
            .replace(/&quot;/g, '"')
            .replace(/&amp;/g, "&")
            .replace(/&lt;/g, "<")
            .replace(/&gt;/g, ">")
            .replace(/&apos;/g, "'");
    for (const m of text.matchAll(/<glyph\b([^>]*)\/>/g)) {
        const attrs = m[1];
        const u = /\sunicode="([^"]*)"/.exec(attrs);
        if (u === null) continue;
        const chars = [...decode(u[1])];
        if (chars.length !== 1) continue; // ligatures are not used
        const adv = /horiz-adv-x="([\d.-]+)"/.exec(attrs)?.[1] ?? fallbackAdvance;
        const d = (/\sd="([^"]*)"/.exec(attrs)?.[1] ?? "").replace(/\s+/g, " ").trim();
        lines.push(`${chars[0].codePointAt(0)} ${adv} ${d}`);
    }
    return lines.join("\n");
}

write(
    "relief",
    `Relief SingleLine, Copyright 2021 The Relief SingleLine Project Authors
(https://github.com/isdat-type/Relief-SingleLine), SIL Open Font License 1.1
(see THIRD_PARTY_NOTICES.md).`,
    svgFont("ReliefSingleLineSVG-Regular.svg"),
);
